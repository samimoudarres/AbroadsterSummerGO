export const DEFAULT_SCHOOL_ACCENT = '#175864';

export function brandColorForName(name: string): string | null {
  const key = name.trim().toLowerCase();
  if (SCHOOL_BRAND_COLORS[key]) return SCHOOL_BRAND_COLORS[key];
  // Partial contains match for longer labels
  for (const [k, hex] of Object.entries(SCHOOL_BRAND_COLORS)) {
    if (key.includes(k) || k.includes(key)) return hex;
  }
  return null;
}
